import * as fs from "fs";
import * as path from "path";
import { getAllFnpSpells } from "../lib/config/spells/fnp-spell-database";
import { SPELLS } from "../lib/config/spells/spell-database";
import { getAllSpells } from "../lib/src/model/spell-item/spell-reference";
import { addFieldToDatabase } from "./lib/spell-database-writer";
import { proposeRange, rangeText, type SplRange } from "./lib/spell-range";
import { ResourceReader } from "./lib/spell-saves";
import { readTlk } from "./lib/tlk";

// Audits the range of each SPELLS entry (lib/config/spells/spell-database.ts) and Faiths and Powers
// spell (lib/config/spells/fnp-spell-database.ts) against a game install: the SPL's first header
// and the "Range:" line of its description, as shipped (the BIFs alone) and with the install's mods
// (override first). A touch or short range spell should declare a short range, see proposeRange.
//
// Writes assets/spells/spell-range-report.md. With --write, also adds the proposed range to the
// entries that don't declare one. A declared value is never changed.
//
// Run: ts-node scripts/extract-spell-ranges.ts [--write] [--game <dir>]

const DEFAULT_GAME = "C:/Games/BG2EE";
const DATABASE = path.join("lib", "config", "spells", "spell-database.ts");
const FNP_DATABASE = path.join("lib", "config", "spells", "fnp-spell-database.ts");
const REPORT = path.join("assets", "spells", "spell-range-report.md");
const SPL_TYPE = 0x3ee;

function parseArgs(): { gameDir: string; write: boolean } {
  const args = process.argv.slice(2);
  const idx = args.indexOf("--game");
  return { gameDir: idx >= 0 ? args[idx + 1] : DEFAULT_GAME, write: args.includes("--write") };
}

function splRange(
  reader: ResourceReader,
  tlk: (strref: number) => string | undefined,
  file: string,
): SplRange | undefined {
  const spl = reader.read(file, SPL_TYPE, "SPL");
  if (!spl?.readUInt16LE(0x68)) return undefined;
  const header = spl.readUInt32LE(0x64);
  return {
    range: spl.readUInt16LE(header + 0x0e),
    target: spl.readUInt8(header + 0x0c),
    text: rangeText(tlk(spl.readInt32LE(0x50)) ?? ""),
  };
}

const describe = (state: SplRange | undefined) =>
  state ? `${state.range} (${state.text ?? "no text"})` : "-";

interface Row {
  key: string;
  file: string;
  database: string;
  vanilla?: SplRange;
  modded?: SplRange;
  declared?: number;
  proposed?: number;
  /** The minimum range its allies check sets */
  alliesRange?: number;
}

function collect(
  spells: ReturnType<typeof getAllSpells>,
  database: string,
  readers: ResourceReader[],
  tlk: (strref: number) => string | undefined,
): Row[] {
  return spells.map((spell) => {
    const file = spell.file.toUpperCase();
    const [vanilla, modded] = readers.map((reader) => splRange(reader, tlk, file));
    return {
      file,
      database,
      vanilla,
      modded,
      key: spell.key,
      declared: spell.range,
      proposed: proposeRange(file, spell, [vanilla, modded]),
      alliesRange: spell.alliesCheck?.range,
    };
  });
}

function writeReport(rows: Row[]) {
  const table = (list: Row[]) => [
    "| Spell | File | Vanilla | Modded | Declared | Proposed |",
    "|---|---|---|---|---|---|",
    ...list.map(
      (row) =>
        `| ${row.key} | ${row.file} | ${describe(row.vanilla)} | ${describe(row.modded)} | ${row.declared ?? ""} | ${row.proposed ?? ""} |`,
    ),
  ];
  const differing = rows.filter(
    (row) => row.proposed !== undefined && row.proposed !== row.declared,
  );
  const unproposed = rows.filter((row) => row.declared !== undefined && row.proposed === undefined);
  const missing = rows.filter((row) => !row.vanilla && !row.modded);
  const conflicting = rows.filter(
    (row) =>
      row.declared !== undefined &&
      row.alliesRange !== undefined &&
      row.alliesRange >= row.declared,
  );
  fs.writeFileSync(
    REPORT,
    [
      "# Spell ranges",
      "",
      "Generated by `scripts/extract-spell-ranges.ts`. Vanilla and Modded: the SPL's first header",
      "range, and the `Range:` line of its description. Declared: the database's `range`, the",
      "script's Range() gate. Proposed: what a touch or short range spell should declare (see",
      "`proposeRange`), nothing for a longer range. Run the script with `--write` to add the",
      "missing ones; a declared value is a decision, kept as is.",
      "",
      `## To declare (${differing.length})`,
      "",
      ...table(differing),
      "",
      `## Declared range not above the allies check (${conflicting.length})`,
      "",
      "The allies check sets a minimum range: such a spell is only cast by a caster safe from it",
      "(see `StatementBuilderService.closeRangeFallback`), never otherwise.",
      "",
      ...table(conflicting),
      "",
      `## Declared, for another reason than touch or short range (${unproposed.length})`,
      "",
      ...table(unproposed),
      "",
      `## Not in the install (${missing.length})`,
      "",
      ...table(missing),
      "",
      `## All entries (${rows.length})`,
      "",
      ...table(rows),
      "",
    ].join("\n"),
  );
  return differing;
}

function main() {
  const { gameDir, write } = parseArgs();
  const tlk = readTlk(fs.readFileSync(path.join(gameDir, "lang", "en_US", "dialog.tlk")));
  const readers = [new ResourceReader(gameDir, false), new ResourceReader(gameDir, true)];
  const rows = [
    ...collect(getAllSpells(SPELLS), DATABASE, readers, tlk),
    ...collect(getAllFnpSpells(), FNP_DATABASE, readers, tlk),
  ];
  const differing = writeReport(rows);
  console.log(`${differing.length} of ${rows.length} entries to declare (see ${REPORT})`);
  if (!write) return;
  for (const database of [DATABASE, FNP_DATABASE]) {
    const values = differing
      .filter((row) => row.database === database && row.declared === undefined)
      .map((row) => ({ file: row.file, key: row.key, value: String(row.proposed) }));
    fs.writeFileSync(
      database,
      addFieldToDatabase(fs.readFileSync(database, "utf-8"), "range", values),
    );
    console.log(`added range to ${values.length} entries of ${database}`);
  }
}

main();
