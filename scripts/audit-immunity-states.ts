import * as fs from "fs";
import * as path from "path";
import { CHECKED_IMMUNITY_STATES } from "../lib/config/immunity-config";
import { clabAbilities, grantedStates, immuneOpcodes, read2da } from "./lib/immunity-states";
import { ResourceReader } from "./lib/spell-saves";

// Lists what the core component's install pass (WeiduCoreService.generateImmunityStates) gives a
// game: which spells and items gain which immunity spell state, and so which kits - through their
// CLAB abilities - the AI sees as immune. Reads an install with its mods (override first).
//
// Writes assets/spells/immunity-states-report.md.
//
// Run: ts-node scripts/audit-immunity-states.ts   (pass --game <dir> to read another install)

const DEFAULT_GAME = "C:/Games/BG2EETest";
const REPORT = path.join("assets", "spells", "immunity-states-report.md");
const TYPES = { SPL: 0x3ee, ITM: 0x3ed, "2DA": 0x3f4 } as const;

function parseArgs(): { gameDir: string } {
  const args = process.argv.slice(2);
  const idx = args.indexOf("--game");
  return { gameDir: idx >= 0 ? args[idx + 1] : DEFAULT_GAME };
}

/** Every spell and item gaining a state: the files per state, and the states per spell. */
function scanStates(reader: ResourceReader) {
  const byState = new Map<string, string[]>();
  const spellStates = new Map<string, string[]>();
  for (const extension of ["SPL", "ITM"] as const) {
    // this mod's own files set their states
    const names = reader.names(TYPES[extension], extension).filter((n) => !n.startsWith("JA"));
    for (const name of names) {
      const file = reader.read(name, TYPES[extension], extension);
      const states = file ? grantedStates(immuneOpcodes(file), CHECKED_IMMUNITY_STATES) : [];
      if (extension === "SPL" && states.length) spellStates.set(name, states);
      for (const state of states) {
        byState.set(state, [...(byState.get(state) ?? []), `${name}.${extension}`]);
      }
    }
  }
  return { byState, spellStates };
}

function main() {
  const { gameDir } = parseArgs();
  const reader = new ResourceReader(gameDir, true);
  const text = (name: string) => reader.read(name, TYPES["2DA"], "2DA")?.toString("latin1");
  const { byState, spellStates } = scanStates(reader);

  // kits, through the abilities of their CLAB table
  const kits = read2da(text("KITLIST") ?? "").flatMap(({ values }) => {
    const clab = values.ABILITIES;
    if (!clab || clab === "*") return [];
    const clabText = text(clab);
    if (!clabText) return [];
    const abilities = clabAbilities(clabText).filter((spell) => spellStates.has(spell));
    const states = [...new Set(abilities.flatMap((spell) => spellStates.get(spell) ?? []))];
    return [{ kit: values.ROWNAME ?? "?", clab, abilities, states }];
  });
  const immuneKits = kits.filter(({ states }) => states.length);

  fs.writeFileSync(
    REPORT,
    [
      "# Immunity spell states",
      "",
      "Generated by `scripts/audit-immunity-states.ts` from `" + gameDir + "`: what the core",
      "component's install pass gives this game. A spell or item immune (opcode 101) to an",
      "immunity's first prevented opcode also sets the immunity's spell state, which the AI's",
      "spell checks test. Kits gain them through their CLAB abilities (`AP_`).",
      "",
      `## Kits (${immuneKits.length} of ${kits.length})`,
      "",
      "| Kit | CLAB | States | From |",
      "|---|---|---|---|",
      ...immuneKits.map(
        ({ kit, clab, abilities, states }) =>
          `| ${kit} | ${clab} | ${states.join(", ")} | ${abilities.join(", ")} |`,
      ),
      "",
      "## Spells and items, per state",
      "",
      ...CHECKED_IMMUNITY_STATES.flatMap(({ state, opcode }) => {
        const files = byState.get(state) ?? [];
        return [
          `### ${state} (immune to opcode ${opcode}): ${files.length}`,
          "",
          files.join(", "),
          "",
        ];
      }),
    ].join("\n"),
  );
  console.log(
    `${immuneKits.length} kits and ${spellStates.size} spells gain states (see ${REPORT})`,
  );
}

main();
