import * as fs from "fs";
import * as path from "path";
import { buildAllCreatures } from "../lib/creatures";
import logService from "../lib/src/services/log.service";
import mainService from "../lib/src/services/main.service";
import stateService from "../lib/src/services/state.service";
import { fitThreat } from "../lib/src/services/experience/threat/threat-xp";
import { threatSamples } from "./lib/experience-proposals";

// Fits the threat XP (XP = Table 31 x s x threat^k) on the base creatures with both a 2e book XP
// (xpv2e) and an in-game XP, and writes the result to threat-fit.ts (read by threatXp).
//
// Run: npm run fit-threat

const FIT_PATH = path.join(
  process.cwd(),
  "lib",
  "src",
  "services",
  "experience",
  "threat",
  "threat-fit.ts",
);

/** Three decimals */
function round(value: number): number {
  return Math.round(value * 1000) / 1000;
}

async function main() {
  logService.filePath = path.join(process.cwd(), "fit-threat.log");
  logService.init();
  await stateService.init();
  mainService.checkPresets();
  mainService.checkSpells();
  const samples = threatSamples(buildAllCreatures());
  const fit = fitThreat(samples);
  const s = round(fit.s);
  const k = round(fit.k);
  const source =
    "// Generated by `npm run fit-threat`; do not edit by hand.\n" +
    'import { ThreatFit } from "./threat-xp";\n\n' +
    `export const THREAT_FIT: ThreatFit = { s: ${s}, k: ${k}, samples: ${fit.samples} };\n`;
  fs.writeFileSync(FIT_PATH, source, "utf-8");
  console.log(`Wrote ${path.relative(process.cwd(), FIT_PATH)}: s = ${s}, k = ${k}`);
  console.log(`${fit.samples} samples (${samples.length} base creatures with both XP)`);
}

main().catch((e: unknown) => {
  console.error(e);
  process.exit(1);
});
