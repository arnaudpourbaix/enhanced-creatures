import * as fs from "fs";
import * as path from "path";
import { SPELLS } from "../lib/config/spells/spell-database";
import { SaveTypeEnum } from "../lib/src/model/spell-item/effect.enums";
import {
  getAllSpells,
  spellFiles,
  type SpellSaves,
} from "../lib/src/model/spell-item/spell-reference";
import {
  addSavesToDatabase,
  mergeStates,
  readerSource,
  ResourceReader,
  spellSaves,
} from "./lib/spell-saves";

// Extracts the saving throws negating each SPELLS entry (lib/config/spells/spell-database.ts) from
// a game install, for TriggerFactory.saveChecks - see negatingSaves for the rules, the same as for
// the spells this mod creates. Reads each spell twice: as shipped (the BIFs alone) and with the
// install's mods (override first), since a mod can change a spell's saves (e.g. Spell Revisions),
// then merges both (see mergeStates), along with the entry's variant files.
//
// Writes assets/spells/spell-saves-report.md: every entry's saves in both states, and whether the
// database's agree. With --write, also adds the extracted saves to the entries that don't declare
// any yet (an entry's own `saves` is never changed: see addSavesToDatabase).
//
// Run: ts-node scripts/extract-spell-saves.ts [--write] [--game <dir>]

const DEFAULT_GAME = "C:/Games/BG2EE";
const DATABASE = path.join("lib", "config", "spells", "spell-database.ts");
const REPORT = path.join("assets", "spells", "spell-saves-report.md");

function parseArgs(): { gameDir: string; write: boolean } {
  const args = process.argv.slice(2);
  const idx = args.indexOf("--game");
  return { gameDir: idx >= 0 ? args[idx + 1] : DEFAULT_GAME, write: args.includes("--write") };
}

const SAVE_NAMES: Record<number, string> = {
  [SaveTypeEnum.Spell]: "Spell",
  [SaveTypeEnum.Breath]: "Breath",
  [SaveTypeEnum.ParalyzePoisonDeath]: "ParalyzePoisonDeath",
  [SaveTypeEnum.RodStaffWand]: "RodStaffWand",
  [SaveTypeEnum.PetrifyPolymorph]: "PetrifyPolymorph",
};

function describe(saves: SpellSaves | undefined): string {
  if (saves === undefined) return "(missing)";
  if (!saves.length) return "-";
  return saves
    .map(({ types, bonus }) => {
      const names = types.map((t) => SAVE_NAMES[t]).join("/");
      if (!bonus) return names;
      return bonus > 0 ? `${names} +${bonus}` : `${names} ${bonus}`;
    })
    .join(" + ");
}

const same = (a: SpellSaves | undefined, b: SpellSaves | undefined) =>
  JSON.stringify(a ?? []) === JSON.stringify(b ?? []);

interface Row {
  key: string;
  /** The entry's own file */
  file: string;
  /** Per file of the entry (its own, then its variants'): the saves in both states */
  states: string;
  extracted: SpellSaves;
  database?: SpellSaves;
}

function writeReport(rows: Row[]) {
  const table = (list: Row[]) => [
    "| Spell | File | Vanilla / modded, per file | Extracted | Database |",
    "|---|---|---|---|---|",
    ...list.map(
      (row) =>
        `| ${row.key} | ${row.file} | ${row.states} | ${describe(row.extracted)} | ${row.database === undefined ? "(none)" : describe(row.database)} |`,
    ),
  ];
  const differing = rows.filter((row) => !same(row.extracted, row.database));
  fs.writeFileSync(
    REPORT,
    [
      "# Spell saving throws",
      "",
      "Generated by `scripts/extract-spell-saves.ts`. A target is skipped only when it can't fail",
      "any listed save (`+` separates effects, `/` the save types of one effect, then the bonus to",
      "the target's roll, the lowest across caster levels). `-`: the spell can't be escaped (no",
      "save check), `(missing)`: the spell doesn't exist in that state, `(none)`: the database",
      "entry doesn't declare saves (none checked).",
      "",
      `## Database differing from the game (${differing.length})`,
      "",
      "Run the script with `--write` to add the missing ones; a declared value (e.g. Dispel",
      "Magic's none) is a decision, kept as is.",
      "",
      ...table(differing),
      "",
      `## All entries (${rows.length})`,
      "",
      ...table(rows),
      "",
    ].join("\n"),
  );
  return differing.length;
}

function main() {
  const { gameDir, write } = parseArgs();
  const vanilla = readerSource(new ResourceReader(gameDir, false));
  const modded = readerSource(new ResourceReader(gameDir, true));
  const rows: Row[] = getAllSpells(SPELLS).map((spell) => {
    const files = spellFiles(spell).map((file) => file.toUpperCase());
    // a variant only exists with its mod
    const states = files.map((file, i) => ({
      file,
      vanilla: i ? undefined : spellSaves(vanilla, file),
      modded: spellSaves(modded, file),
    }));
    return {
      key: spell.key,
      file: files[0],
      states: states
        .map((s) => {
          const both = `${describe(s.vanilla)} / ${describe(s.modded)}`;
          return files.length > 1 ? s.file + ": " + both : both;
        })
        .join("<br>"),
      extracted: mergeStates(...states.flatMap((s) => [s.vanilla, s.modded])),
      database: spell.saves,
    };
  });
  const differing = writeReport(rows);
  console.log(`${differing} of ${rows.length} entries differ from the game (see ${REPORT})`);
  if (!write) return;
  const missing = new Map(
    rows
      .filter((row) => row.database === undefined && row.extracted.length)
      .map((row) => [row.file, row.extracted]),
  );
  fs.writeFileSync(DATABASE, addSavesToDatabase(fs.readFileSync(DATABASE, "utf-8"), missing));
  console.log(`added saves to ${missing.size} entries of ${DATABASE}: format it with prettier`);
}

main();
