/** Entry folder name under `lib/pnp-monster/`: the kebab-case enum key ("clay-golem"). */
export const ENTRY_FOLDERS: Record<EntryEnum, string> = mapEntries((id) =>
  EntryEnum[id].replace(/(?<=[a-z0-9])([A-Z])/g, "-$1").toLowerCase(),
);
